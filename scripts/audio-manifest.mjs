#!/usr/bin/env node
/**
 * Lists whatever audio actually exists in public/audio so the player does not
 * depend on one exact filename. Runs before every build.
 *
 * Files under 20 KB are treated as broken: renaming or editing a binary
 * through a web editor silently replaces it with a couple of bytes, which is
 * easy to miss and produces a player that appears to work but never sounds.
 */
import { readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const audioDir = join(root, 'public', 'audio');
const outFile = join(root, 'src', 'lib', 'audioManifest.ts');

const AUDIO = /\.(mp3|m4a|aac|ogg|oga|wav|flac)$/i;
const MIN_BYTES = 20 * 1024;

const tracks = [];
const broken = [];

if (existsSync(audioDir)) {
  for (const name of readdirSync(audioDir).sort()) {
    if (!AUDIO.test(name)) continue;
    const size = statSync(join(audioDir, name)).size;
    if (size < MIN_BYTES) {
      broken.push({ name, size });
      continue;
    }
    tracks.push({ name, size });
  }
}

for (const file of broken) {
  console.warn(
    `\n  ⚠  public/audio/${file.name} is only ${file.size} bytes and cannot be real audio.` +
      `\n     Re-upload it: dragging a file into GitHub's web editor corrupts binaries.\n`
  );
}

if (tracks.length === 0 && broken.length === 0) {
  console.log('  No audio in public/audio — the music control will stay hidden.');
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/audio-manifest.mjs — do not edit by hand.
export type AudioTrack = { name: string; url: string; size: number };

export const AUDIO_TRACKS: AudioTrack[] = ${JSON.stringify(
    tracks.map((t) => ({ name: t.name, url: `/audio/${encodeURIComponent(t.name)}`, size: t.size })),
    null,
    2
  )};

export const BROKEN_AUDIO: { name: string; size: number }[] = ${JSON.stringify(broken, null, 2)};
`
);

console.log(`  Audio manifest: ${tracks.length} usable, ${broken.length} broken.`);
